#!/usr/bin/env python3
"""Generate Figure 3 (gate-impact bar chart) for the PSDL Qeios article.

Run from the repository root with the project venv:
    venv/bin/python docs/figures/make_figures.py

Figures 1, 2, and 4 are diagrams maintained in
docs/figures/psdl_figures.drawio — edit them in draw.io and re-export
PNG + SVG; they are NOT generated by this script.

Numbers come from scripts/experiment_aki_mimic_results.json and the
pre-gate run reported in the article text. The two-series palette
(#ff725c / #4269d0) passes the colorblind-safety checks of the dataviz
validator; every bar is direct-labeled.
"""

import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

OUT = pathlib.Path(__file__).parent

INK = "#1f2430"
BLUE = "#4269d0"     # gated (KDIGO-correct) series
ORANGE = "#ff725c"   # ungated series

plt.rcParams.update({
    "font.size": 9.5,
    "font.family": "DejaVu Sans",
    "svg.fonttype": "none",
})


def fig3():
    stages = ["Stage 1", "Stage 2", "Stage 3"]
    ungated = [16955, 5375, 11917]   # pre-gate scenario, same protocol
    gated = [16961, 5372, 8119]      # aki_definition_met gate applied

    fig, ax = plt.subplots(figsize=(7, 4.4))
    x = range(len(stages))
    w = 0.36
    b1 = ax.bar([i - w / 2 for i in x], ungated, w, color=ORANGE,
                label="without AKI-definition gate", edgecolor="white",
                linewidth=1)
    b2 = ax.bar([i + w / 2 for i in x], gated, w, color=BLUE,
                label="with AKI-definition gate (KDIGO-correct)",
                edgecolor="white", linewidth=1)
    for bars in (b1, b2):
        for r in bars:
            ax.annotate(f"{int(r.get_height()):,}",
                        (r.get_x() + r.get_width() / 2, r.get_height()),
                        textcoords="offset points", xytext=(0, 3),
                        ha="center", fontsize=8.5, color=INK)
    ax.annotate("−3,798 patients:\nchronic Cr ≥ 4.0 mg/dL,\nno acute change",
                xy=(2 + w / 2 + 0.12, 8500), xytext=(1.30, 14200),
                fontsize=8.5, color=INK, ha="left",
                arrowprops=dict(arrowstyle="-|>", color=INK, lw=1))
    ax.set_xticks(list(x))
    ax.set_xticklabels(stages)
    ax.set_ylabel("patients (exclusive stage assignment)")
    ax.set_ylim(0, 19000)
    ax.set_yticks(range(0, 20000, 4000))
    ax.set_yticklabels([f"{v:,}" for v in range(0, 20000, 4000)])
    ax.spines[["top", "right"]].set_visible(False)
    ax.yaxis.grid(True, color="#e5e7eb", lw=0.8)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, fontsize=8.5, loc="lower center",
              bbox_to_anchor=(0.5, 1.0), ncol=2)
    for ext, kw in (("png", {"dpi": 300}), ("pdf", {}), ("svg", {})):
        fig.savefig(OUT / f"fig3_gate_impact.{ext}", bbox_inches="tight",
                    facecolor="white", **kw)
    plt.close(fig)
    print("wrote fig3_gate_impact")


if __name__ == "__main__":
    fig3()
